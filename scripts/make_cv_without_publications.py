#!/usr/bin/env python3
"""Write Marine_Denolle_CV_no_publications.yaml: the full CV minus publications.

The copy is derived from Marine_Denolle_CV.yaml on every run (the deploy
workflow calls this before rendering), so it never drifts from the full CV.
It drops the publications legend and the publications list; everything else,
including the Research Impact Summary rows, is kept.

Usage:
    python scripts/make_cv_without_publications.py
"""

import re
import sys
from pathlib import Path

CV_DIR = Path(__file__).resolve().parent.parent / "marine-cv-docs"
SOURCE = CV_DIR / "Marine_Denolle_CV.yaml"
TARGET = CV_DIR / "Marine_Denolle_CV_no_publications.yaml"

# From the "Phase 5b: Publications" comment through the publications include.
PUBLICATIONS_BLOCK = re.compile(
    r"^[ \t]*# Phase 5b: Publications.*?^[ \t]*publications: !include publications_section\.yaml[ \t]*\n",
    re.M | re.S,
)

HEADER = (
    "# AUTO-GENERATED by scripts/make_cv_without_publications.py from\n"
    "# Marine_Denolle_CV.yaml: do not edit; change the full CV instead.\n"
)


def build(source_text: str) -> str:
    text, n = PUBLICATIONS_BLOCK.subn("", source_text, count=1)
    if n != 1:
        raise ValueError("publications block not found in Marine_Denolle_CV.yaml")
    if re.search(r"^\s*publications(_legend)?:", text, re.M):
        raise ValueError("publications section still present after removal")
    # Point the default render paths at this file's own outputs.
    text = text.replace("rendercv_output/Marine_Denolle_CV.", "rendercv_output/Marine_Denolle_CV_no_publications.")
    return HEADER + text


def main() -> int:
    try:
        TARGET.write_text(build(SOURCE.read_text(encoding="utf-8")), encoding="utf-8")
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
